//! Manual pages in the `man` macro package: `dogfish-TOOL.1` for each tool
//! and `dogfish.1` for the multicall binary. They are lint-clean for
//! `groff -man -ww -z` and `mandoc -Tlint` (`cargo xtask docs-gen` checks
//! with whichever is installed).

use std::fmt::Write as _;

use super::help::{Block, Entry, Help, Item};
use super::{Doc, Manual, Opt, SWITCH_DOCS, failure_status, in_gnu_coreutils};

/// Escapes `s` for a troff text line: backslashes, hyphens (which are
/// minus signs in options and file names), and characters outside ASCII.
fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\e"),
            '-' => out.push_str("\\-"),
            '\'' => out.push_str("\\(aq"),
            '`' => out.push_str("\\(ga"),
            '\t' => out.push_str("        "),
            c if c.is_ascii() && !c.is_ascii_control() => out.push(c),
            c if c.is_ascii() => {}
            c => {
                let _ = write!(out, "\\[u{:04X}]", u32::from(c));
            }
        }
    }
    out
}

/// One text line: escaped, and kept from being read as a request.
fn text_line(out: &mut String, s: &str) {
    let e = esc(s);
    if e.starts_with('.') || e.starts_with('\'') {
        out.push_str("\\&");
    }
    out.push_str(&e);
    out.push('\n');
}

/// The `.TH` date: `SOURCE_DATE_EPOCH` as YYYY-MM-DD, so that a page is the
/// same however often it is generated; empty without it.
fn page_date() -> String {
    let Some(secs) = std::env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|v| v.trim().parse::<i64>().ok())
    else {
        return String::new();
    };
    let (y, m, d) = civil_from_days(secs.div_euclid(86_400));
    format!("{y:04}-{m:02}-{d:02}")
}

/// Howard Hinnant's `civil_from_days`: the proleptic Gregorian date `days`
/// after 1970-01-01.
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    let y = yoe + era * 400 + i64::from(m <= 2);
    (y, m, d)
}

fn header(out: &mut String, title: &str, generated_by: &str) {
    let _ = writeln!(
        out,
        ".\\\" Generated by `{generated_by}`; do not edit.\n\
         .TH {} 1 \"{}\" \"GNU/Dogfish {}\" \"User Commands\"\n.nh",
        title.to_ascii_uppercase(),
        page_date(),
        env!("CARGO_PKG_VERSION"),
    );
}

/// The prose blocks of a section; `first` says whether the section has had
/// no paragraph yet (no `.PP` right after `.SH`).
fn blocks<'a>(out: &mut String, blocks: impl IntoIterator<Item = &'a Block>, first: &mut bool) {
    for b in blocks {
        if !*first {
            out.push_str(".PP\n");
        }
        *first = false;
        match b {
            Block::Text(lines) => lines.iter().for_each(|l| text_line(out, l)),
            Block::Pre(lines) => {
                out.push_str(".nf\n");
                lines.iter().for_each(|l| text_line(out, l));
                out.push_str(".fi\n");
            }
        }
    }
}

/// `\fB\-a\fR, \fB\-\-all\fR`-style option heads.
fn head(parts: &[(String, String)]) -> String {
    parts
        .iter()
        .map(|(spelling, arg)| {
            let arg = arg.trim_start();
            let sep = if arg.starts_with('<') { " " } else { "" };
            if arg.is_empty() {
                format!("\\fB{}\\fR", esc(spelling))
            } else {
                format!("\\fB{}\\fR{sep}\\fI{}\\fR", esc(spelling), esc(arg))
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn entry(out: &mut String, m: &Manual, help: &Help, e: &Entry, listed: &mut Vec<String>) {
    let mut parts = e.head.clone();
    // Synonyms the help names nowhere at the start of an entry
    // (`--desc` for `-r`), listed with the first entry of their option.
    for o in m.opts.iter().filter(|o| e.groups.contains(&o.group)) {
        for s in o.spellings() {
            if !help.mentions(&s) && !listed.contains(&s) {
                listed.push(s.clone());
                parts.push((s, String::new()));
            }
        }
    }
    out.push_str(".TP\n");
    out.push_str(&head(&parts));
    out.push('\n');
    if e.desc.is_empty() {
        text_line(out, "(no description)");
    }
    for l in &e.desc {
        text_line(out, l);
    }
}

/// The OPTIONS section: the help's entries and the prose among them, the
/// Dogfish switches the tool takes, and the options the help leaves out.
fn options(out: &mut String, m: &Manual, help: &Help) {
    out.push_str(".SH OPTIONS\n");
    for l in &help.options_intro {
        text_line(out, l);
    }
    let last_entry = help
        .options
        .iter()
        .rposition(|it| matches!(it, Item::Entry(_)));
    let mut listed = Vec::new();
    for (i, it) in help.options.iter().enumerate() {
        match it {
            Item::Entry(e) => entry(out, m, help, e, &mut listed),
            // The options come first, so prose here follows an entry and
            // starts a paragraph of its own.
            Item::Block(b) => blocks(out, [b], &mut false),
        }
        if Some(i) == last_entry {
            defaults_and_switches(out, m, help);
        }
    }
    if last_entry.is_none() {
        defaults_and_switches(out, m, help);
    }
    other_options(out, m, help);
}

/// Every spelling of `o` and its synonyms, without arguments.
fn group_spellings(m: &Manual, o: &Opt) -> Vec<(String, String)> {
    m.opts
        .iter()
        .filter(|p| p.group == o.group)
        .flat_map(|p| p.spellings())
        .map(|s| (s, String::new()))
        .collect()
}

/// The options the help text does not describe, in one paragraph.
fn other_options(out: &mut String, m: &Manual, help: &Help) {
    let mut done = Vec::new();
    let mut heads = Vec::new();
    for o in &m.opts {
        if matches!(m.doc(help, o), Doc::Other) && !done.contains(&o.group) {
            done.push(o.group);
            heads.push(head(&group_spellings(m, o)));
        }
    }
    if heads.is_empty() {
        return;
    }
    out.push_str(".SS \"Other options\"\n");
    text_line(
        out,
        "These are accepted as GNU accepts them, but --help does not describe them \
         (the GNU manual does); Dogfish may report some as not supported yet:",
    );
    out.push_str(&heads.join(",\n"));
    out.push_str(".\n");
}

/// `--help` and `--version` where the help text leaves them out, then the
/// Dogfish switches.
fn defaults_and_switches(out: &mut String, m: &Manual, help: &Help) {
    for o in &m.opts {
        if let Doc::Default(desc) = m.doc(help, o) {
            out.push_str(".TP\n");
            out.push_str(&head(&group_spellings(m, o)));
            out.push('\n');
            text_line(out, desc);
        }
    }
    for s in &m.switches {
        if help.mentions(&format!("--{}", s.long)) {
            continue;
        }
        let (spelling, arg) = s.head.split_at(s.long.len() + 2);
        out.push_str(".TP\n");
        out.push_str(&head(&[(spelling.to_string(), arg.to_string())]));
        out.push('\n');
        text_line(out, s.desc);
    }
}

/// The EXIT STATUS section: the help's own list, or what the tool does.
fn exit_status(out: &mut String, tool: &str, help: &Help) {
    out.push_str(".SH \"EXIT STATUS\"\n");
    let failure = failure_status(tool).to_string();
    let list: Vec<(String, String)> = if !help.exit_status.is_empty() {
        help.exit_status.clone()
    } else {
        let pairs: &[(&str, &str)] = match tool {
            "true" => &[("0", "always")],
            "false" => &[("1", "always")],
            "ls" => &[
                ("0", "if OK,"),
                ("1", "if minor problems (e.g., cannot access subdirectory),"),
                (
                    "2",
                    "if serious trouble (e.g., cannot access command-line argument).",
                ),
            ],
            "sort" => &[
                ("0", "if no error occurred,"),
                ("1", "if invoked with -c or -C and the input is not sorted,"),
                ("2", "if an error occurred."),
            ],
            "printenv" => &[
                ("0", "if every VARIABLE is set,"),
                ("1", "if some VARIABLE is not set,"),
                ("2", "if an error occurred."),
            ],
            _ => &[
                ("0", "on success,"),
                (failure.as_str(), "if an error occurred."),
            ],
        };
        pairs
            .iter()
            .map(|(a, b)| (a.to_string(), b.to_string()))
            .collect()
    };
    for (code, meaning) in list {
        out.push_str(".TP\n");
        text_line(out, &code);
        text_line(out, &meaning);
    }
}

/// `dogfish-TOOL.1`.
pub(crate) fn page(m: &Manual) -> String {
    let help = m.parsed_help();
    let mut out = String::new();
    let name = format!("dogfish-{}", m.tool);
    header(
        &mut out,
        &name,
        &format!("dogfish --generate man {}", m.tool),
    );

    out.push_str(".SH NAME\n");
    text_line(
        &mut out,
        &format!("{name} - {}", lower_first(&help.summary())),
    );

    out.push_str(".SH SYNOPSIS\n");
    let usage = if help.usage.is_empty() {
        vec![format!("{} [OPTION]...", m.tool)]
    } else {
        help.usage.clone()
    };
    for (i, u) in usage.iter().enumerate() {
        if i > 0 {
            out.push_str(".br\n");
        }
        let (prog, args) = u.split_once(' ').unwrap_or((u, ""));
        let _ = writeln!(out, ".B {}", esc(prog));
        if !args.is_empty() {
            text_line(&mut out, args);
        }
    }
    let first_args = usage[0].split_once(' ').map_or("", |(_, a)| a);
    out.push_str(".br\n");
    let _ = writeln!(out, ".B dogfish {}", esc(m.tool));
    if !first_args.is_empty() {
        text_line(&mut out, first_args);
    }

    out.push_str(".SH DESCRIPTION\n");
    let mut first = true;
    blocks(&mut out, &help.description, &mut first);
    if !first {
        out.push_str(".PP\n");
    }
    text_line(
        &mut out,
        &format!(
            "This is the GNU/Dogfish {0}, run as {0} through a link to the dogfish binary or as dogfish {0}. \
             When its output is not a terminal it behaves as GNU coreutils 9.4 does, byte for byte; \
             on a terminal it may show richer output.",
            m.tool
        ),
    );

    options(&mut out, m, &help);
    exit_status(&mut out, m.tool, &help);

    out.push_str(".SH \"SEE ALSO\"\n");
    if in_gnu_coreutils(m.tool) {
        out.push_str(".BR dogfish (1),\n");
        let _ = writeln!(out, ".BR {} (1)", esc(m.tool));
        out.push_str(".PP\n");
        text_line(
            &mut out,
            &format!(
                "The GNU original is documented in {0}(1) and by info coreutils \u{2019}{0} invocation\u{2019}.",
                m.tool
            ),
        );
    } else {
        out.push_str(".BR dogfish (1)\n");
    }
    out
}

/// Lower-cases the first letter of a sentence, unless it starts a word in
/// capitals (`FILE`, `NDJSON`).
fn lower_first(s: &str) -> String {
    let mut chars = s.chars();
    match (chars.next(), chars.next()) {
        (Some(a), Some(b)) if a.is_ascii_uppercase() && !b.is_ascii_uppercase() => {
            let mut out = a.to_ascii_lowercase().to_string();
            out.push_str(&s[1..]);
            out
        }
        _ => s.to_string(),
    }
}

/// `dogfish.1`: the multicall binary, its utilities and the switches they
/// share.
pub(crate) fn multicall_page(manuals: &[Manual]) -> String {
    let mut out = String::new();
    header(&mut out, "dogfish", "dogfish --generate man dogfish");
    out.push_str(".SH NAME\n");
    text_line(
        &mut out,
        "dogfish - GNU/Dogfish, GNU-compatible and object-aware coreutils in one binary",
    );
    out.push_str(".SH SYNOPSIS\n");
    for (i, (prog, args)) in [
        ("dogfish", "UTILITY [ARGUMENT]..."),
        ("UTILITY", "[ARGUMENT]..."),
        ("dogfish", "--list | --help | --version"),
    ]
    .iter()
    .enumerate()
    {
        if i > 0 {
            out.push_str(".br\n");
        }
        let _ = writeln!(out, ".B {}", esc(prog));
        text_line(&mut out, args);
    }
    out.push_str(".SH DESCRIPTION\n");
    for (i, para) in [
        "dogfish runs the utility named by its first argument, or, when it is run through a link \
         named after a utility (ls, or df-ls), the utility named by the link. \
         dogfish install-links DIR creates such links.",
        "When their output is not a terminal, the utilities match GNU coreutils 9.4 byte for byte: \
         output, diagnostics and exit status. On a terminal they may show colours, tables and \
         other rich output. Several read and write NDJSON object streams (--json), \
         and cp, mv and rm --safe record what they do, so that dogfish undo can reverse it.",
    ]
    .iter()
    .enumerate()
    {
        if i > 0 {
            out.push_str(".PP\n");
        }
        text_line(&mut out, para);
    }
    out.push_str(".SH UTILITIES\n");
    for m in manuals {
        let desc = crate::ALL_TOOLS
            .iter()
            .find(|(n, _, _)| *n == m.tool)
            .map_or("", |(_, _, d)| d);
        out.push_str(".TP\n");
        let _ = writeln!(out, ".B {}", esc(m.tool));
        text_line(&mut out, desc);
        let _ = writeln!(out, ".br\nSee\n.BR dogfish\\-{} (1).", esc(m.tool));
    }
    out.push_str(".SH OPTIONS\n");
    for (opt, desc) in [
        ("--help", "print a summary of the utilities and exit"),
        ("--version", "print the version and exit"),
        (
            "--list",
            "print the name of each utility, one per line, and exit",
        ),
        (
            "--generate man UTILITY|bash|zsh|fish",
            "print the manual page of UTILITY (dogfish for this one), or the completion \
             script for a shell, and exit",
        ),
    ] {
        out.push_str(".TP\n");
        let (opt, args) = opt.split_once(' ').unwrap_or((opt, ""));
        let _ = write!(out, "\\fB{}\\fR", esc(opt));
        if !args.is_empty() {
            let _ = write!(out, " \\fI{}\\fR", esc(args));
        }
        out.push('\n');
        text_line(&mut out, desc);
    }
    out.push_str(".SS \"Options most utilities take\"\n");
    text_line(
        &mut out,
        "Each utility page lists the ones it takes; echo, printf, true, false and yes take none, \
         as their GNU versions treat every argument as an operand.",
    );
    for (_, s) in SWITCH_DOCS {
        out.push_str(".TP\n");
        let (spelling, arg) = s.head.split_at(s.long.len() + 2);
        out.push_str(&head(&[(spelling.to_string(), arg.to_string())]));
        out.push('\n');
        text_line(&mut out, s.desc);
    }
    out.push_str(".SH ENVIRONMENT\n");
    for (var, desc) in [
        (
            "DOGFISH_STATS",
            "when set, every utility that takes --stats behaves as if it were given",
        ),
        (
            "NO_COLOR",
            "when set, rich terminal output is plain unless colour is asked for with --color=always",
        ),
        (
            "DOGFISH_HOME",
            "where the undo journal and the rm --safe trash live (default: ~/.dogfish)",
        ),
        (
            "DOGFISH_UNDO",
            "off, 0, false or no: cp and mv record nothing for dogfish undo (and keep no backups of what they overwrite)",
        ),
        (
            "DOGFISH_JOURNAL_MAX",
            "the number of operations the undo journal keeps",
        ),
        (
            "DOGFISH_BACKUP_LIMIT",
            "the largest file cp and mv back up before overwriting it (a size such as 100M)",
        ),
        (
            "POSIXLY_CORRECT",
            "as in GNU: options end at the first operand, among other things",
        ),
    ] {
        out.push_str(".TP\n");
        let _ = writeln!(out, ".B {var}");
        text_line(&mut out, desc);
    }
    out.push_str(".SH \"EXIT STATUS\"\n");
    text_line(
        &mut out,
        "That of the utility run; 0 after --help, --version or --list; \
         1 for an unknown utility.",
    );
    out.push_str(".SH \"SEE ALSO\"\n");
    let n = manuals.len();
    for (i, m) in manuals.iter().enumerate() {
        let comma = if i + 1 < n { "," } else { "" };
        let _ = writeln!(out, ".BR dogfish\\-{} (1){comma}", esc(m.tool));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_troff() {
        assert_eq!(esc(r"a\b-c 'd' `e`"), r"a\eb\-c \(aqd\(aq \(gae\(ga");
        assert_eq!(esc("…"), r"\[u2026]");
        let mut out = String::new();
        text_line(&mut out, ".hidden");
        text_line(&mut out, "'quote");
        assert_eq!(out, "\\&.hidden\n\\(aqquote\n");
    }

    #[test]
    fn dates_from_the_epoch() {
        assert_eq!(civil_from_days(0), (1970, 1, 1));
        assert_eq!(civil_from_days(19_723), (2024, 1, 1));
        assert_eq!(civil_from_days(11_016), (2000, 2, 29));
    }

    #[test]
    fn pages_have_every_section() {
        for m in super::super::all() {
            let p = page(&m);
            for section in [
                ".SH NAME\n",
                ".SH SYNOPSIS\n",
                ".SH DESCRIPTION\n",
                ".SH OPTIONS\n",
                ".SH \"EXIT STATUS\"\n",
                ".SH \"SEE ALSO\"\n",
            ] {
                assert!(p.contains(section), "{}: {section}", m.tool);
            }
            assert!(p.contains(&format!(".TH DOGFISH-{} 1", m.tool.to_ascii_uppercase())));
            // Every line is a request or text that cannot be read as one,
            // and nothing outside ASCII reaches troff.
            for line in p.lines() {
                assert!(!line.is_empty(), "{}: blank line", m.tool);
                assert!(line.is_ascii(), "{}: {line}", m.tool);
                assert!(!line.starts_with('\''), "{}: {line}", m.tool);
                if let Some(req) = line.strip_prefix('.') {
                    let name = req.split(' ').next().unwrap_or_default();
                    assert!(
                        [
                            "\\\"", "TH", "nh", "SH", "SS", "PP", "TP", "B", "BR", "br", "nf", "fi"
                        ]
                        .contains(&name),
                        "{}: {line}",
                        m.tool
                    );
                }
            }
        }
    }

    #[test]
    fn ls_page_documents_its_options() {
        let m = super::super::manual("ls").unwrap();
        let p = page(&m);
        assert!(p.contains(
            ".TP\n\\fB\\-a\\fR, \\fB\\-\\-all\\fR\ndo not ignore entries starting with .\n"
        ));
        assert!(p.contains("\\fB\\-\\-block\\-size\\fR\\fI=SIZE\\fR"));
        assert!(p.contains("\\fB\\-\\-stats\\fR\n"));
        assert!(p.contains(".SH NAME\ndogfish\\-ls \\- list information about the FILEs\n"));
        assert!(p.contains(".B dogfish ls\n[OPTION]... [FILE]...\n"));
    }

    #[test]
    fn the_multicall_page_lists_every_utility() {
        let all = super::super::all();
        let p = multicall_page(&all);
        for m in &all {
            assert!(p.contains(&format!(".BR dogfish\\-{} (1)", esc(m.tool))));
        }
    }
}
